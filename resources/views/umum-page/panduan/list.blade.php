            <div class="accordion-body">
                <div class="ki-sub">
                    <div class="ki-sub-title">Pengertian Umum Desain Industri</div>
                    <p>Desain Industri adalah suatu kreasi tentang bentuk, konfigurasi atau komposisi garis atau
                        warna, atau garis dan warna, atau gabungan daripadanya yang berbentuk tiga dimensi atau dua
                        dimensi yang memberikan kesan estetis dan dapat diwujudkan dalam pola tiga dimensi atau dua
                        dimensi serta dapat dipakai untuk menghasilkan suatu produk, barang, komoditas industri atau
                        kerajinan tangan.</p>
                </div>

                <div class="ki-sub">
                    <div class="ki-sub-title">Desain Industri yang Dapat Didaftarkan</div>
                    <ol class="ki-list">
                        <li>
                            Desain Industri yang memiliki kebaruan (novelty), dengan catatan jika pada tanggal
                            penerimaan permohonan pendaftaran Desain Industri tersebut tidak sama dengan
                            pengungkapan Desain Industri yang telah ada sebelumnya.
                        </li>
                        <li>
                            Tidak bertentangan dengan peraturan perundang-undangan yang berlaku, ketertiban umum,
                            agama, atau kesusilaan.
                        </li>
                    </ol>
                </div>

                <div class="ki-sub">
                    <div class="ki-sub-title">Masa Pelindungan Desain Industri</div>
                    <p>Pemegang hak desain industri memiliki hak eksklusif untuk melaksanakan hak yang dimilikinya
                        dan untuk melarang orang lain tanpa persetujuannya membuat, memakai, menjual, mengimpor,
                        mengekspor, dan/atau mengedarkan produk-produk terkait.</p>
                </div>

