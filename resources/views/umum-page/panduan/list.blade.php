            <div class="accordion-body">
                <div class="ki-sub">
                    <div class="ki-sub-title">Definisi Hak Cipta</div>
                    <p>Hak Cipta merupakan salah satu bagian dari kekayaan intelektual yang memiliki ruang lingkup
                        objek dilindungi paling luas, karena mencakup ilmu pengetahuan, seni dan sastra (art and
                        literary) yang di dalamnya mencakup pula program komputer. Perkembangan ekonomi kreatif yang
                        menjadi salah satu andalan Indonesia dan pesatnya perkembangan teknologi informasi dan
                        komunikasi mengharuskan adanya pembaruan Undang-Undang Hak Cipta, mengingat Hak Cipta
                        menjadi basis terpenting dari ekonomi kreatif nasional.</p>
                </div>

                <div class="ki-sub">
                    <div class="ki-sub-title">Ciptaan yang Dapat Dilindungi</div>
                    <ol class="ki-list">
                        <li>Karya Tulis</li>
                        <li>Karya Lainnya</li>
                        <li>Program Komputer</li>
                    </ol>
                </div>

                <div class="ki-sub ki-sub-last">
                    <div class="ki-sub-title">Masa Pelindungan Ciptaan</div>
                    <ol class="ki-list">
                        <li>Perlindungan Hak Cipta: seumur hidup Pencipta + 70 tahun.</li>
                        <li>Program Komputer: 50 tahun sejak pertama kali dipublikasikan.</li>
                        <li>Pelaku: 50 tahun sejak pertama kali dipertunjukkan.</li>
                        <li>Produser Rekaman: 50 tahun sejak Ciptaan difiksasikan.</li>
                        <li>Lembaga Penyiaran: 20 tahun sejak pertama kali disiarkan.</li>
                    </ol>
                </div>

